-- P6. Lecturas por tabla de TODA esta sesión (P4a + P4b + P5 + lo anterior).
--     El COMMIT sólo refresca la foto de MON$; la sesión sigue en solo lectura.
COMMIT;
SET TRANSACTION READ ONLY ISOLATION LEVEL READ COMMITTED;
SELECT CAST(TRIM(t.MON$TABLE_NAME) AS VARCHAR(31)) AS TABLA,
       r.MON$RECORD_IDX_READS AS LECTURAS_INDICE, r.MON$RECORD_SEQ_READS AS LECTURAS_SECUENCIALES
FROM MON$ATTACHMENTS a
JOIN MON$TABLE_STATS t ON t.MON$STAT_ID = a.MON$STAT_ID
JOIN MON$RECORD_STATS r ON r.MON$STAT_ID = t.MON$RECORD_STAT_ID
WHERE a.MON$ATTACHMENT_ID = CURRENT_CONNECTION
  AND (r.MON$RECORD_IDX_READS + r.MON$RECORD_SEQ_READS) > 0
  AND t.MON$TABLE_NAME NOT STARTING WITH 'RDB$' AND t.MON$TABLE_NAME NOT STARTING WITH 'MON$'
ORDER BY 2 DESC;

-- Control final: ninguna sentencia nuestra quedó colgada.
SELECT COUNT(*) AS STMTS_ACTIVAS FROM MON$STATEMENTS
WHERE MON$STATE = 1 AND MON$ATTACHMENT_ID <> CURRENT_CONNECTION;
