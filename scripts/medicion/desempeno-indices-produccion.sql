SET TRANSACTION READ ONLY ISOLATION LEVEL READ COMMITTED;
-- Índices del tablero de desempeño (migración 000065). SOLO LECTURA: ningún
-- INSERT/UPDATE/DELETE/DDL. Correr ANTES y DESPUÉS de aplicar 000065 (y antes
-- y después de cada recálculo de estadísticas, docs/ops/estadisticas-indices.md)
-- y guardar las dos salidas con fecha.
--
-- Uso (despliegue-produccion.md §11; scp y luego isql -i, nunca por stdin):
--   isql.exe -user <USUARIO> -password <CONTRASENA> localhost:<RUTA_FDB> ^
--     -i C:\desempeno-indices-produccion.sql -o C:\desempeno-indices-<antes|despues>.txt
--
-- La salida de P4/P5 trae todas las filas de la consulta (cientos o miles de
-- líneas): por eso -o a archivo. Lo que se compara son las líneas PLAN,
-- "Elapsed time", "Reads", "Fetches" y P6.
--
-- La zona es la que más pagos tuvo en los últimos 7 días. Se calcula UNA vez
-- en P3 y se guarda en una variable de sesión (RDB$SET_CONTEXT, no escribe en
-- la base); P4/P5 la leen con RDB$GET_CONTEXT, que Firebird trata como valor
-- fijo y usa para IDX_MSP_PAGOS_ZONA_FECHA igual que el parámetro del API.
-- NO poner la subconsulta de la zona dentro de cada consulta: en dev
-- (2026-10-15) esa subconsulta sola costaba 5.35 millones de fetches (recorre
-- MSP_PAGOS_VENTAS por IDX_MSP_PAGOS_ZONA_UPDATED) y tapaba lo que se mide.
-- Para medir otra zona: cambiar el SELECT de P3 por
--   SELECT RDB$SET_CONTEXT('USER_SESSION', 'ZONA', <zona>) FROM RDB$DATABASE;
-- Si el PLAN de P4 no muestra IDX_MSP_PAGOS_ZONA_FECHA para P, la medición no
-- representa al API.

-- P1. Caché de páginas y configuración que la gobierna.
SELECT MON$PAGE_BUFFERS AS PAGE_BUFFERS, MON$PAGE_SIZE AS PAGE_SIZE,
       MON$PAGE_BUFFERS * MON$PAGE_SIZE / 1048576 AS CACHE_MB,
       MON$ODS_MAJOR AS ODS_MAJOR, MON$ODS_MINOR AS ODS_MINOR
FROM MON$DATABASE;
SELECT CAST(RDB$CONFIG_NAME AS VARCHAR(30)) AS PARAMETRO,
       CAST(RDB$CONFIG_VALUE AS VARCHAR(40)) AS VALOR,
       RDB$CONFIG_IS_SET AS FIJADO_EN_CONF
FROM RDB$CONFIG
WHERE RDB$CONFIG_NAME IN ('DefaultDbCachePages', 'ServerMode', 'UseFileSystemCache',
                          'FileSystemCacheThreshold', 'TempCacheLimit');
SELECT RDB$GET_CONTEXT('SYSTEM', 'ENGINE_VERSION') AS MOTOR FROM RDB$DATABASE;
SELECT COUNT(*) AS CONEXIONES FROM MON$ATTACHMENTS;

-- P2. Índices de las tablas del tablero: selectividad guardada vs real.
--     Si 000065 no está aplicada, los tres índices nuevos simplemente no salen.
SELECT CAST(TRIM(i.RDB$RELATION_NAME) AS VARCHAR(31)) AS TABLA,
       CAST(TRIM(i.RDB$INDEX_NAME) AS VARCHAR(40)) AS INDICE,
       s.RDB$FIELD_POSITION AS POS, CAST(TRIM(s.RDB$FIELD_NAME) AS VARCHAR(31)) AS CAMPO,
       i.RDB$STATISTICS AS SELECTIVIDAD_GUARDADA
FROM RDB$INDICES i JOIN RDB$INDEX_SEGMENTS s ON s.RDB$INDEX_NAME = i.RDB$INDEX_NAME
WHERE i.RDB$RELATION_NAME IN ('MSP_PAGOS_RECIBIDOS', 'MSP_VISITAS', 'MSP_PAGOS_VENTAS')
ORDER BY 1, 2, 3;
SELECT COUNT(*) AS FILAS,
       COUNT(DISTINCT IMPTE_DOCTO_CC_ID) AS DISTINTOS_IMPTE,
       COUNT(DISTINCT DOCTO_CC_ID) AS DISTINTOS_DOCTO,
       COUNT(DISTINCT ESTADO) AS DISTINTOS_ESTADO,
       SUM(CASE WHEN IMPTE_DOCTO_CC_ID IS NULL THEN 1 ELSE 0 END) AS IMPTE_NULOS
FROM MSP_PAGOS_RECIBIDOS;
SELECT ESTADO, COUNT(*) AS N FROM MSP_PAGOS_RECIBIDOS GROUP BY ESTADO;

-- P3. Zona y volumen que se van a medir (se fija aquí para P4 y P5).
SELECT FIRST 1 x.ZONA_CLIENTE_ID AS ZONA, COUNT(*) AS PAGOS_7_DIAS FROM MSP_PAGOS_VENTAS x
WHERE x.FECHA >= DATEADD(-7 DAY TO CURRENT_DATE)
GROUP BY x.ZONA_CLIENTE_ID ORDER BY COUNT(*) DESC;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'ZONA',
         (SELECT FIRST 1 x.ZONA_CLIENTE_ID FROM MSP_PAGOS_VENTAS x
           WHERE x.FECHA >= DATEADD(-7 DAY TO CURRENT_DATE)
           GROUP BY x.ZONA_CLIENTE_ID ORDER BY COUNT(*) DESC)) AS FIJADA
FROM RDB$DATABASE;
SELECT RDB$GET_CONTEXT('USER_SESSION', 'ZONA') AS ZONA_MEDIDA FROM RDB$DATABASE;

SET PLAN ON;
SET STATS ON;
SET COUNT ON;

-- P4a. queryPagosAplicados (desempenofb/actividades_repo.go), 7 días.
--      Texto idéntico al del repositorio salvo los tres parámetros.
--      Lo que hay que mirar: las líneas PLAN (PR2 ...) y PLAN (PR3 ...).
--      Antes de 000065 en dev: PLAN (PR2 ORDER PK_MSP_PAGOS_RECIBIDOS INDEX (...)).
SELECT
  p.IMPTE_DOCTO_CC_ID,
  COALESCE(dc.DOCTO_CC_ID, p.DOCTO_CC_ID),
  COALESCE(i.DOCTO_CC_ACR_ID, p.DOCTO_CC_ACR_ID),
  COALESCE(dc.CLIENTE_ID, p.CLIENTE_ID),
  c.NOMBRE,
  COALESCE(dc.CONCEPTO_CC_ID, p.CONCEPTO_CC_ID),
  COALESCE(p.FECHA, CAST(dc.FECHA AS TIMESTAMP)),
  CAST(COALESCE(i.IMPORTE + i.IMPUESTO, p.IMPORTE + p.IMPUESTO) AS NUMERIC(18,2)),
  COALESCE(i.APLICADO, p.APLICADO),
  dc.LAT,
  dc.LON,
  dc.COBRADOR_ID,
  (SELECT MIN(fcd.FORMA_COBRO_ID) FROM FORMAS_COBRO_DOCTOS fcd
    WHERE fcd.NOM_TABLA_DOCTOS = 'DOCTOS_CC' AND fcd.DOCTO_ID = p.DOCTO_CC_ID),
  (SELECT pv.FOLIO FROM DOCTOS_PV pv WHERE pv.DOCTO_PV_ID = (
      SELECT des.DOCTO_FTE_ID FROM DOCTOS_ENTRE_SIS des
      WHERE des.CLAVE_SIS_FTE = 'PV' AND des.CLAVE_SIS_DEST = 'CC'
        AND des.DOCTO_DEST_ID = COALESCE(i.DOCTO_CC_ACR_ID, p.DOCTO_CC_ACR_ID) ROWS 1) ROWS 1),
  (SELECT des.DOCTO_FTE_ID FROM DOCTOS_ENTRE_SIS des
      WHERE des.CLAVE_SIS_FTE = 'PV' AND des.CLAVE_SIS_DEST = 'CC'
        AND des.DOCTO_DEST_ID = COALESCE(i.DOCTO_CC_ACR_ID, p.DOCTO_CC_ACR_ID) ROWS 1),
  pr.ID,
  pr.COBRADOR_ID,
  pr.COBRADOR,
  pr.FORMA_COBRO_ID,
  pr.LAT,
  pr.LON,
  pr.RECEIVED_AT,
  u.FIREBASE_UID,
  (SELECT COUNT(*) FROM MSP_PAGOS_IMAGENES im WHERE im.PAGO_ID = pr.ID)
FROM MSP_PAGOS_VENTAS p
LEFT JOIN IMPORTES_DOCTOS_CC i ON i.IMPTE_DOCTO_CC_ID = p.IMPTE_DOCTO_CC_ID
LEFT JOIN DOCTOS_CC dc ON dc.DOCTO_CC_ID = p.DOCTO_CC_ID
LEFT JOIN CLIENTES c   ON c.CLIENTE_ID  = COALESCE(dc.CLIENTE_ID, p.CLIENTE_ID)
LEFT JOIN MSP_PAGOS_RECIBIDOS pr ON pr.ID = COALESCE(
  (SELECT MIN(pr2.ID) FROM MSP_PAGOS_RECIBIDOS pr2 WHERE pr2.IMPTE_DOCTO_CC_ID = p.IMPTE_DOCTO_CC_ID),
  (SELECT MIN(pr3.ID) FROM MSP_PAGOS_RECIBIDOS pr3
    WHERE pr3.DOCTO_CC_ID = p.DOCTO_CC_ID AND pr3.IMPTE_DOCTO_CC_ID IS NULL))
LEFT JOIN MSP_USUARIOS u ON u.ID = pr.CREATED_BY
WHERE p.ZONA_CLIENTE_ID = CAST(RDB$GET_CONTEXT('USER_SESSION', 'ZONA') AS INTEGER)
  AND p.FECHA >= DATEADD(-7 DAY TO CURRENT_DATE)
  AND p.FECHA <= CURRENT_TIMESTAMP
  AND COALESCE(i.CANCELADO, p.CANCELADO) = 'N'
  AND COALESCE(dc.CONCEPTO_CC_ID, p.CONCEPTO_CC_ID) IN (87327, 27969);

-- P4b. Lo mismo, 92 días.
SELECT
  p.IMPTE_DOCTO_CC_ID,
  COALESCE(dc.DOCTO_CC_ID, p.DOCTO_CC_ID),
  COALESCE(i.DOCTO_CC_ACR_ID, p.DOCTO_CC_ACR_ID),
  COALESCE(dc.CLIENTE_ID, p.CLIENTE_ID),
  c.NOMBRE,
  COALESCE(dc.CONCEPTO_CC_ID, p.CONCEPTO_CC_ID),
  COALESCE(p.FECHA, CAST(dc.FECHA AS TIMESTAMP)),
  CAST(COALESCE(i.IMPORTE + i.IMPUESTO, p.IMPORTE + p.IMPUESTO) AS NUMERIC(18,2)),
  COALESCE(i.APLICADO, p.APLICADO),
  dc.LAT,
  dc.LON,
  dc.COBRADOR_ID,
  (SELECT MIN(fcd.FORMA_COBRO_ID) FROM FORMAS_COBRO_DOCTOS fcd
    WHERE fcd.NOM_TABLA_DOCTOS = 'DOCTOS_CC' AND fcd.DOCTO_ID = p.DOCTO_CC_ID),
  (SELECT pv.FOLIO FROM DOCTOS_PV pv WHERE pv.DOCTO_PV_ID = (
      SELECT des.DOCTO_FTE_ID FROM DOCTOS_ENTRE_SIS des
      WHERE des.CLAVE_SIS_FTE = 'PV' AND des.CLAVE_SIS_DEST = 'CC'
        AND des.DOCTO_DEST_ID = COALESCE(i.DOCTO_CC_ACR_ID, p.DOCTO_CC_ACR_ID) ROWS 1) ROWS 1),
  (SELECT des.DOCTO_FTE_ID FROM DOCTOS_ENTRE_SIS des
      WHERE des.CLAVE_SIS_FTE = 'PV' AND des.CLAVE_SIS_DEST = 'CC'
        AND des.DOCTO_DEST_ID = COALESCE(i.DOCTO_CC_ACR_ID, p.DOCTO_CC_ACR_ID) ROWS 1),
  pr.ID,
  pr.COBRADOR_ID,
  pr.COBRADOR,
  pr.FORMA_COBRO_ID,
  pr.LAT,
  pr.LON,
  pr.RECEIVED_AT,
  u.FIREBASE_UID,
  (SELECT COUNT(*) FROM MSP_PAGOS_IMAGENES im WHERE im.PAGO_ID = pr.ID)
FROM MSP_PAGOS_VENTAS p
LEFT JOIN IMPORTES_DOCTOS_CC i ON i.IMPTE_DOCTO_CC_ID = p.IMPTE_DOCTO_CC_ID
LEFT JOIN DOCTOS_CC dc ON dc.DOCTO_CC_ID = p.DOCTO_CC_ID
LEFT JOIN CLIENTES c   ON c.CLIENTE_ID  = COALESCE(dc.CLIENTE_ID, p.CLIENTE_ID)
LEFT JOIN MSP_PAGOS_RECIBIDOS pr ON pr.ID = COALESCE(
  (SELECT MIN(pr2.ID) FROM MSP_PAGOS_RECIBIDOS pr2 WHERE pr2.IMPTE_DOCTO_CC_ID = p.IMPTE_DOCTO_CC_ID),
  (SELECT MIN(pr3.ID) FROM MSP_PAGOS_RECIBIDOS pr3
    WHERE pr3.DOCTO_CC_ID = p.DOCTO_CC_ID AND pr3.IMPTE_DOCTO_CC_ID IS NULL))
LEFT JOIN MSP_USUARIOS u ON u.ID = pr.CREATED_BY
WHERE p.ZONA_CLIENTE_ID = CAST(RDB$GET_CONTEXT('USER_SESSION', 'ZONA') AS INTEGER)
  AND p.FECHA >= DATEADD(-92 DAY TO CURRENT_DATE)
  AND p.FECHA <= CURRENT_TIMESTAMP
  AND COALESCE(i.CANCELADO, p.CANCELADO) = 'N'
  AND COALESCE(dc.CONCEPTO_CC_ID, p.CONCEPTO_CC_ID) IN (87327, 27969);

-- P4c. queryPagosPendientes, 92 días. Mirar PLAN (PR ...): antes de 000065 en
--      dev era INDEX (IDX_MSP_PAGOS_RECIBIDOS) (sólo FECHA, 84,873 lecturas) y
--      con estadísticas al día INDEX (IDX_MSP_PAGOS_RECIBIDOS, IDX_MSP_PAGOS_REC_ESTADO).
SELECT
  pr.ID, pr.CARGO_DOCTO_CC_ID, pr.CLIENTE_ID, c.NOMBRE, pr.CONCEPTO_CC_ID, pr.FECHA,
  CAST(pr.IMPORTE AS NUMERIC(18,2)), pr.FORMA_COBRO_ID, pr.LAT, pr.LON, pr.COBRADOR_ID,
  pr.COBRADOR, pr.INTENTOS, pr.RECEIVED_AT, u.FIREBASE_UID,
  (SELECT COUNT(*) FROM MSP_PAGOS_IMAGENES im WHERE im.PAGO_ID = pr.ID),
  (SELECT pv.FOLIO FROM DOCTOS_PV pv WHERE pv.DOCTO_PV_ID = (
      SELECT des.DOCTO_FTE_ID FROM DOCTOS_ENTRE_SIS des
      WHERE des.CLAVE_SIS_FTE = 'PV' AND des.CLAVE_SIS_DEST = 'CC'
        AND des.DOCTO_DEST_ID = pr.CARGO_DOCTO_CC_ID ROWS 1) ROWS 1),
  (SELECT des.DOCTO_FTE_ID FROM DOCTOS_ENTRE_SIS des
      WHERE des.CLAVE_SIS_FTE = 'PV' AND des.CLAVE_SIS_DEST = 'CC'
        AND des.DOCTO_DEST_ID = pr.CARGO_DOCTO_CC_ID ROWS 1)
FROM MSP_PAGOS_RECIBIDOS pr
JOIN MSP_SALDOS_VENTAS s ON s.DOCTO_CC_ID = pr.CARGO_DOCTO_CC_ID
LEFT JOIN CLIENTES c     ON c.CLIENTE_ID  = pr.CLIENTE_ID
LEFT JOIN MSP_USUARIOS u ON u.ID = pr.CREATED_BY
WHERE pr.ESTADO = 'P'
  AND s.ZONA_CLIENTE_ID = CAST(RDB$GET_CONTEXT('USER_SESSION', 'ZONA') AS INTEGER)
  AND pr.FECHA >= DATEADD(-92 DAY TO CURRENT_DATE)
  AND pr.FECHA <= CURRENT_TIMESTAMP
  AND NOT EXISTS (SELECT 1 FROM MSP_PAGOS_VENTAS p2
    LEFT JOIN IMPORTES_DOCTOS_CC i2 ON i2.IMPTE_DOCTO_CC_ID = p2.IMPTE_DOCTO_CC_ID
    WHERE p2.IMPTE_DOCTO_CC_ID = pr.IMPTE_DOCTO_CC_ID
      AND COALESCE(i2.CANCELADO, p2.CANCELADO) = 'N')
  AND NOT EXISTS (SELECT 1 FROM IMPORTES_DOCTOS_CC i3
    JOIN MSP_PAGOS_VENTAS p3 ON p3.IMPTE_DOCTO_CC_ID = i3.IMPTE_DOCTO_CC_ID
    WHERE i3.DOCTO_CC_ID = pr.DOCTO_CC_ID
      AND COALESCE(i3.CANCELADO, p3.CANCELADO) = 'N');

-- P4d. queryVisitas, 92 días (misma zona). Mirar PLAN (V ...): después de
--      000065 debe ser INDEX (IDX_MSP_VISITAS_ZONA_FECHA).
SELECT
  v.ID, v.CLIENTE_ID, c.NOMBRE, v.FECHA, v.TIPO_VISITA, v.NOTA, v.LAT, v.LNG,
  v.COBRADOR_ID, v.COBRADOR, v.IMPTE_DOCTO_CC_ID,
  (SELECT COUNT(*) FROM MSP_VISITAS_IMAGENES im WHERE im.VISITA_ID = v.ID),
  (SELECT pv.FOLIO FROM DOCTOS_PV pv WHERE pv.DOCTO_PV_ID = (
      SELECT des.DOCTO_FTE_ID FROM DOCTOS_ENTRE_SIS des
      WHERE des.CLAVE_SIS_FTE = 'PV' AND des.CLAVE_SIS_DEST = 'CC'
        AND des.DOCTO_DEST_ID = v.IMPTE_DOCTO_CC_ID ROWS 1) ROWS 1),
  (SELECT des.DOCTO_FTE_ID FROM DOCTOS_ENTRE_SIS des
      WHERE des.CLAVE_SIS_FTE = 'PV' AND des.CLAVE_SIS_DEST = 'CC'
        AND des.DOCTO_DEST_ID = v.IMPTE_DOCTO_CC_ID ROWS 1)
FROM MSP_VISITAS v
LEFT JOIN CLIENTES c ON c.CLIENTE_ID = v.CLIENTE_ID
WHERE v.ZONA_CLIENTE_ID = CAST(RDB$GET_CONTEXT('USER_SESSION', 'ZONA') AS INTEGER)
  AND v.FECHA >= DATEADD(-92 DAY TO CURRENT_DATE)
  AND v.FECHA <= CURRENT_TIMESTAMP;

-- P5. pagoRecibidoDelAbono (clientesfb/queries.go) sobre los abonos de esa
--     zona en 7 días: la subconsulta del detalle de pago, en lote.
SELECT pv.IMPTE_DOCTO_CC_ID, p.DOCTO_CC_ID,
  COALESCE(
    (SELECT MIN(pr2.ID) FROM IMPORTES_DOCTOS_CC i2
       JOIN MSP_PAGOS_RECIBIDOS pr2 ON pr2.IMPTE_DOCTO_CC_ID = i2.IMPTE_DOCTO_CC_ID
      WHERE i2.DOCTO_CC_ID = p.DOCTO_CC_ID
        AND i2.TIPO_IMPTE = 'R'
        AND i2.CANCELADO  = 'N'),
    (SELECT MIN(pr3.ID) FROM MSP_PAGOS_RECIBIDOS pr3
      WHERE pr3.DOCTO_CC_ID = p.DOCTO_CC_ID
        AND pr3.IMPTE_DOCTO_CC_ID IS NULL))
FROM MSP_PAGOS_VENTAS pv
JOIN DOCTOS_CC p ON p.DOCTO_CC_ID = pv.DOCTO_CC_ID
WHERE pv.ZONA_CLIENTE_ID = CAST(RDB$GET_CONTEXT('USER_SESSION', 'ZONA') AS INTEGER) AND pv.FECHA >= DATEADD(-7 DAY TO CURRENT_DATE) AND pv.FECHA <= CURRENT_TIMESTAMP;

SET PLAN OFF;
