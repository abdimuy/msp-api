// The ventas module's OpenAPI contract is GENERATED by Huma from the
// registered operations and their Go DTOs — unlike the auth module, whose
// contract is the hand-written api/openapi.yaml validated by
// internal/auth/infra/authhttp/contract_test.go. api/openapi.yaml declares
// only the auth paths; no ventas path has ever appeared in it.
//
// So the document to validate against is the one the server actually serves
// at /v2/openapi.json. These tests fetch it, parse it with kin-openapi, and
// validate a real request AND a real response of PUT /v2/ventas/{id}/lineas
// against it. That is stricter than asserting the path string is present: a
// DTO field that drifts from the schema fails here.

// ─── rig ────────────────────────────────────────────────────────────────────

// contractLineasRig pairs a router mounted under /v2 (the prefix the generated
// spec advertises as its server) with the spec that same router publishes.
type contractLineasRig struct {
	router http.Handler
	spec   *openapi3.T
	routes routers.Router
}

// newContractLineasRig mounts the ventas module under /v2, fetches the
// generated OpenAPI document from the live router, and builds the kin-openapi
// route matcher over it.
func newContractLineasRig(t *testing.T, cu auth.CurrentUser) *contractLineasRig {
	t.Helper()
	svc, _, _ := testService()
	root := chi.NewRouter()
	root.Route("/v2", func(r chi.Router) {
		r.Use(planter(cu))
		venthttp.MountRouter(r, svc)
	})

	req := httptest.NewRequest(http.MethodGet, "/v2/openapi.json", nil)
	rec := httptest.NewRecorder()
	root.ServeHTTP(rec, req)
	require.Equal(t, http.StatusOK, rec.Code, "the router must publish its generated OpenAPI document")

	loader := openapi3.NewLoader()
	loader.IsExternalRefsAllowed = false
	spec, err := loader.LoadFromData(rec.Body.Bytes())
	require.NoError(t, err, "generated spec must parse")
	require.NoError(t, spec.Validate(t.Context()), "generated spec must be a valid OpenAPI document")

	routesMatcher, err := gorillamux.NewRouter(spec)
	require.NoError(t, err)

	return &contractLineasRig{router: root, spec: spec, routes: routesMatcher}
}

// contractAuthAny accepts any bearer token: the handler-level authn check is
// what these tests exercise, not the token itself.
func contractAuthAny(_ context.Context, _ *openapi3filter.AuthenticationInput) error { return nil }

// exchange validates the request against the spec (for success paths), serves
// it, then validates the response against the spec. Returns the recorder.
func (c *contractLineasRig) exchange(t *testing.T, req *http.Request, wantStatus int) *httptest.ResponseRecorder {
	t.Helper()

	route, pathParams, err := c.routes.FindRoute(req)
	require.NoError(t, err, "generated spec must declare route %s %s", req.Method, req.URL.Path)

	opts := &openapi3filter.Options{
		IncludeResponseStatus: true,
		AuthenticationFunc:    contractAuthAny,
	}

	var bodyBytes []byte
	if req.Body != nil {
		bodyBytes, err = io.ReadAll(req.Body)
		require.NoError(t, err)
		req.Body = io.NopCloser(bytes.NewReader(bodyBytes))
	}

	// Only positive paths are shape-validated on the way in — the negative
	// cases deliberately send bodies the spec rejects.
	if wantStatus >= 200 && wantStatus < 300 {
		require.NoError(t, openapi3filter.ValidateRequest(req.Context(), &openapi3filter.RequestValidationInput{
			Request: req, PathParams: pathParams, Route: route, Options: opts,
		}), "request must be valid per the generated spec")
		req.Body = io.NopCloser(bytes.NewReader(bodyBytes))
	}

	rec := httptest.NewRecorder()
	c.router.ServeHTTP(rec, req)
	require.Equal(t, wantStatus, rec.Code, rec.Body.String())

	require.NoError(t, openapi3filter.ValidateResponse(req.Context(), &openapi3filter.ResponseValidationInput{
		RequestValidationInput: &openapi3filter.RequestValidationInput{
			Request: req, PathParams: pathParams, Route: route, Options: opts,
		},
		Status:  rec.Code,
		Header:  rec.Header(),
		Body:    io.NopCloser(bytes.NewReader(rec.Body.Bytes())),
		Options: opts,
	}), "response must conform to the generated spec: status=%d body=%s", rec.Code, rec.Body.String())
	return rec
}

// seedVentaConComboOnRig creates the combo-bearing venta through the /v2
// router so the contract exchange has a target.
func seedVentaConComboOnRig(t *testing.T, c *contractLineasRig) (string, string) {
	t.Helper()
	body := validCreateBody()
	comboID := uuid.NewString()
	body.Combos = []venthttp.ComboDTO{comboDTO(comboID, "Combo Original")}
	body.Productos = []venthttp.ProductoDTO{comboChildDTO(comboID, 77)}

	req := crearVentaMultipartRequest(t, body)
	req.URL.Path = "/v2" + req.URL.Path
	rec := httptest.NewRecorder()
	c.router.ServeHTTP(rec, req)
	require.Equal(t, http.StatusCreated, rec.Code, rec.Body.String())
	var out venthttp.VentaDTO
	require.NoError(t, json.Unmarshal(rec.Body.Bytes(), &out))
	return out.ID, comboID
}

// jsonReq builds a JSON request under the /v2 prefix.
func jsonReq(t *testing.T, method, target string, body any) *http.Request {
	t.Helper()
	b, err := json.Marshal(body)
	require.NoError(t, err)
	req := httptest.NewRequest(method, target, bytes.NewReader(b))
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer contract-test-token")
	return req
}

