// TestContract_Lineas_DeclaredInSpec asserts the generated document declares
// the operation with the shape callers depend on: PUT, a uuid path param, a
// required JSON body carrying BOTH collections, and a 200 response. It also
// pins that the two endpoints it supersedes are still declared — and now
// marked deprecated rather than removed.
func TestContract_Lineas_DeclaredInSpec(t *testing.T) {
	t.Parallel()
	c := newContractLineasRig(t, fullPerms(uuid.New()))

	item := c.spec.Paths.Find("/ventas/{id}/lineas")
	require.NotNil(t, item, "the generated spec must declare /ventas/{id}/lineas")
	op := item.Put
	require.NotNil(t, op, "the operation must be a PUT")
	assert.Equal(t, "reemplazar-lineas-venta", op.OperationID)
	assert.False(t, op.Deprecated, "the replacement endpoint must not be deprecated")

	require.NotNil(t, op.RequestBody)
	require.NotNil(t, op.RequestBody.Value)
	media := op.RequestBody.Value.Content.Get("application/json")
	require.NotNil(t, media, "the body must be application/json")
	schema := media.Schema.Value
	require.NotNil(t, schema)
	require.Contains(t, schema.Properties, "combos", "the body must carry combos")
	require.Contains(t, schema.Properties, "productos", "the body must carry productos")

	// Every status the handler can actually produce must be declared.
	for _, status := range []string{"200", "401", "403", "404", "409", "422"} {
		assert.NotNil(t, op.Responses.Value(status), "response %s must be declared", status)
	}

	// The superseded endpoints are still there — production runs them.
	for _, path := range []string{"/ventas/{id}/combos", "/ventas/{id}/productos"} {
		old := c.spec.Paths.Find(path)
		require.NotNil(t, old, "%s must keep existing", path)
		require.NotNil(t, old.Put)
		assert.True(t, old.Put.Deprecated, "%s must be marked deprecated, not removed", path)
	}
}

// TestContract_Lineas_RequestAndResponse_OK validates a real exchange — the
// borrar-y-crear edit — in both directions against the generated document.
func TestContract_Lineas_RequestAndResponse_OK(t *testing.T) {
	t.Parallel()
	c := newContractLineasRig(t, fullPerms(uuid.New()))
	id, viejoComboID := seedVentaConComboOnRig(t, c)

	nuevoComboID := uuid.NewString()
	require.NotEqual(t, viejoComboID, nuevoComboID)
	body := venthttp.ReemplazarLineasBody{
		Combos:    []venthttp.ComboDTO{comboDTO(nuevoComboID, "Combo Nuevo")},
		Productos: []venthttp.ProductoDTO{comboChildDTO(nuevoComboID, 99)},
	}

	rec := c.exchange(t, jsonReq(t, http.MethodPut, "/v2/ventas/"+id+"/lineas", body), http.StatusOK)

	var out venthttp.VentaDTO
	require.NoError(t, json.Unmarshal(rec.Body.Bytes(), &out))
	require.Len(t, out.Combos, 1)
	assert.Equal(t, nuevoComboID, out.Combos[0].ID)
}

// TestContract_Lineas_ErrorResponses validates that the problem-details
// documents the handler returns also conform to the declared schemas.
func TestContract_Lineas_ErrorResponses(t *testing.T) {
	t.Parallel()

	t.Run("404", func(t *testing.T) {
		t.Parallel()
		c := newContractLineasRig(t, fullPerms(uuid.New()))
		c.exchange(t, jsonReq(t, http.MethodPut, "/v2/ventas/"+uuid.NewString()+"/lineas", validLineasBody()),
			http.StatusNotFound)
	})

	t.Run("422 referencia invalida", func(t *testing.T) {
		t.Parallel()
		c := newContractLineasRig(t, fullPerms(uuid.New()))
		id, _ := seedVentaConComboOnRig(t, c)
		presente := uuid.NewString()
		body := venthttp.ReemplazarLineasBody{
			Combos: []venthttp.ComboDTO{comboDTO(presente, "Combo Presente")},
			Productos: []venthttp.ProductoDTO{
				comboChildDTO(presente, 1),
				comboChildDTO(uuid.NewString(), 2),
			},
		}
		c.exchange(t, jsonReq(t, http.MethodPut, "/v2/ventas/"+id+"/lineas", body),
			http.StatusUnprocessableEntity)
	})

	t.Run("403", func(t *testing.T) {
		t.Parallel()
		full := newContractLineasRig(t, fullPerms(uuid.New()))
		id, _ := seedVentaConComboOnRig(t, full)
		limited := newContractLineasRig(t, limitedPerms(uuid.New()))
		limited.exchange(t, jsonReq(t, http.MethodPut, "/v2/ventas/"+id+"/lineas", validLineasBody()),
			http.StatusForbidden)
	})
}
