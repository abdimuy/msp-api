-- Orden lógico de los eventos de garantías.
CREATE SEQUENCE GEN_MSP_GA_EVENTO_ORDEN;
COMMIT;

ALTER TABLE MSP_GA_EVENTO ADD ORDEN_EVENTO BIGINT;
COMMIT;

-- Conservar, hasta donde permite el esquema anterior,
-- el orden de lectura de los eventos históricos.
SET TERM ^ ;

EXECUTE BLOCK AS
  DECLARE VARIABLE V_ID CHAR(36) CHARACTER SET ASCII;
BEGIN
  FOR
    SELECT ID
    FROM MSP_GA_EVENTO
    ORDER BY DEVICE_CREATED_AT, CREATED_AT, RDB$DB_KEY
    INTO :V_ID
  DO
  BEGIN
    UPDATE MSP_GA_EVENTO
    SET ORDEN_EVENTO = NEXT VALUE FOR GEN_MSP_GA_EVENTO_ORDEN
    WHERE ID = :V_ID;
  END
END^

SET TERM ; ^
COMMIT;

-- Permitir inserciones desde versiones anteriores del backend.
SET TERM ^ ;

CREATE TRIGGER TR_MSP_GA_EVENTO_BI_ORDEN
FOR MSP_GA_EVENTO
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ORDEN_EVENTO IS NULL) THEN
    NEW.ORDEN_EVENTO = NEXT VALUE FOR GEN_MSP_GA_EVENTO_ORDEN;
END^

SET TERM ; ^
COMMIT;

ALTER TABLE MSP_GA_EVENTO ALTER ORDEN_EVENTO SET NOT NULL;
COMMIT;

CREATE UNIQUE INDEX IDX_MSP_GA_EVENTO_GAR_ORD
ON MSP_GA_EVENTO (GARANTIA_ID, ORDEN_EVENTO);
COMMIT;

INSERT INTO MSP_MIGRATIONS (ID, NAME, APPLIED_AT)
VALUES (72, '000072_orden_msp_ga_evento', CURRENT_TIMESTAMP);
COMMIT;
